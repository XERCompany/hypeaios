        bool test_checksums() noexcept {
            const char digits[] = "123456789";
            return ztext_crc32(digits, 9) == 0xCBF43926u &&
                   ztext_crc32("", 0) == 0 &&
                   ztext_adler32(digits, 9) == 0x091E01DEu &&
                   ztext_adler32("", 0) == 1 &&
                   ztext_adler32(vec_hello, sizeof(vec_hello)) == 0x1A0B045Du;
        }

        bool test_vectors() noexcept {
            hcpp::size_t n = 0;
            bool ok = true;
            // zlib -> hello world
            ok &= ztext_zlib_decode(tb_out, sizeof(tb_out), vec_zlib_hello,
                                    sizeof(vec_zlib_hello), n) &&
                  n == sizeof(vec_hello) &&
                  bytes_equal(tb_out, vec_hello, n);
            // gzip -> hello world
            ok &= ztext_gzip_decode(tb_out, sizeof(tb_out), vec_gzip_hello,
                                    sizeof(vec_gzip_hello), n) &&
                  n == sizeof(vec_hello) &&
                  bytes_equal(tb_out, vec_hello, n);
            // raw deflate -> hello world
            ok &= ztext_inflate(tb_out, sizeof(tb_out), vec_raw_hello,
                                sizeof(vec_raw_hello), n) &&
                  n == sizeof(vec_hello) &&
                  bytes_equal(tb_out, vec_hello, n);
            // dynamic-huffman zlib -> 9000 bytes of the fox phrase
            ok &= ztext_zlib_decode(tb_out, sizeof(tb_out), vec_zlib_fox,
                                    sizeof(vec_zlib_fox), n) &&
                  n == vec_fox_len;
            if (ok && n == vec_fox_len) {
                for (hcpp::size_t i = 0; i < n; ++i)
                    if (tb_out[i] !=
                        static_cast<hcpp::u8>(
                            vec_fox_phrase[i % (sizeof(vec_fox_phrase) - 1)])) {
                        ok = false;
                        break;
                    }
            }
            // stored-block zlib -> bytes(0..255) x4
            ok &= ztext_zlib_decode(tb_out, sizeof(tb_out), vec_zlib_stored,
                                    sizeof(vec_zlib_stored), n) &&
                  n == vec_stored_len;
            if (ok && n == vec_stored_len) {
                for (hcpp::size_t i = 0; i < n; ++i)
                    if (tb_out[i] != static_cast<hcpp::u8>(i & 0xFFu)) {
                        ok = false;
                        break;
                    }
            }
            return ok;
        }

        bool roundtrip_raw(const hcpp::u8 *src, hcpp::size_t len) noexcept {
            hcpp::size_t clen = 0;
            hcpp::size_t dlen = 0;
            if (!ztext_deflate(tb_cmp, sizeof(tb_cmp), src, len, clen))
                return false;
            if (!ztext_inflate(tb_out, sizeof(tb_out), tb_cmp, clen, dlen))
                return false;
            return dlen == len && bytes_equal(tb_out, src, len);
        }

        bool roundtrip_zlib(const hcpp::u8 *src, hcpp::size_t len) noexcept {
            hcpp::size_t clen = 0;
            hcpp::size_t dlen = 0;
            if (!ztext_zlib_encode(tb_cmp, sizeof(tb_cmp), src, len, clen))
                return false;
            if (!ztext_zlib_decode(tb_out, sizeof(tb_out), tb_cmp, clen, dlen))
                return false;
            return dlen == len && bytes_equal(tb_out, src, len);
        }

        bool roundtrip_gzip(const hcpp::u8 *src, hcpp::size_t len) noexcept {
            hcpp::size_t clen = 0;
            hcpp::size_t dlen = 0;
            if (!ztext_gzip_encode(tb_cmp, sizeof(tb_cmp), src, len, clen))
                return false;
            if (!ztext_gzip_decode(tb_out, sizeof(tb_out), tb_cmp, clen, dlen))
                return false;
            return dlen == len && bytes_equal(tb_out, src, len);
        }

        hcpp::size_t fill_text(hcpp::u8 *dst, hcpp::size_t cap) noexcept {
            const char *parts[] = {
                "HypeAI OS ztext: the quick brown fox jumps over the lazy dog. ",
                "DEFLATE packs literals and 32KB-window back-references. ",
                "pack my box with five dozen liquor jugs! ",
            };
            hcpp::size_t n = 0;
            while (n < cap) {
                for (auto *p : parts) {
                    hcpp::size_t l = 0;
                    while (p[l] != 0 && n < cap) dst[n++] = static_cast<hcpp::u8>(p[l++]);
                    if (n >= cap) break;
                }
            }
            return n;
        }

        bool test_roundtrips() noexcept {
            // empty input
            if (!roundtrip_raw(tb_src, 0) || !roundtrip_zlib(tb_src, 0) ||
                !roundtrip_gzip(tb_src, 0))
                return false;
            // single byte
            tb_src[0] = 'Z';
            if (!roundtrip_raw(tb_src, 1)) return false;
            // text
            const hcpp::size_t tlen = fill_text(tb_src, 4096);
            if (!roundtrip_raw(tb_src, tlen)) return false;
            // compressible runs
            for (hcpp::size_t i = 0; i < sizeof(tb_src); ++i)
                tb_src[i] = static_cast<hcpp::u8>('a' + (i / 512) % 26);
            if (!roundtrip_raw(tb_src, sizeof(tb_src))) return false;
            // incompressible-looking binary pattern
            hcpp::u32 seed = 0x12345678u;
            for (hcpp::size_t i = 0; i < sizeof(tb_src); ++i) {
                seed ^= seed << 13;
                seed ^= seed >> 17;
                seed ^= seed << 5;
                tb_src[i] = static_cast<hcpp::u8>(seed & 0xFFu);
            }
            if (!roundtrip_raw(tb_src, sizeof(tb_src))) return false;
            return true;
        }

        bool test_zlib() noexcept {
            const hcpp::size_t tlen = fill_text(tb_src, 2048);
            return roundtrip_zlib(tb_src, tlen);
        }

        bool test_gzip() noexcept {
            const hcpp::size_t tlen = fill_text(tb_src, 2048);
            return roundtrip_gzip(tb_src, tlen);
        }

