    FontGlyph arial_glyph(u32 codepoint) noexcept {
        if (codepoint >= 'a' && codepoint <= 'z') {
            codepoint -= 'a' - 'A';
        }

        size_t low = 0;
        size_t high = arial_glyph_count;
        while (low < high) {
            const size_t mid = low + (high - low) / 2;
            if (arial_entries[mid].codepoint < codepoint) {
                low = mid + 1;
            } else {
                high = mid;
            }
        }

        const u8* rows = arial_blank;
        if (low < arial_glyph_count && arial_entries[low].codepoint == codepoint) {
            rows = arial_entries[low].rows;
        }
        return FontGlyph{rows, 1, 5, 7, 6, 0, 7};
    }

    const FontFace& arial_font() noexcept { return arial; }

